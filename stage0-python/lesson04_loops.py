# ===================================================
# 【原理】自测完再读
# ===================================================
#
# 【先猜 1】0 1 2 3 4。从 0 开始，5 不算，一共 5 个。
#   range(5) 的意思是「给我 5 个数」，不是「数到 5」。
#   为什么从 0 开始？可以理解成「离起点走了几步」—— 第一个就站在起点上，走了 0 步。
#   编程里几乎所有的计数都从 0 开始，下一课的列表也是，早点习惯。
#
#   range(起点, 终点)：包含起点，不包含终点。range(1, 6) 是 1 到 5。
#   记法：range(a, b) 一共 b - a 个数。
#
#   还有第三个参数「步长」，不写就默认每次 +1 往上数：
#       range(10, 0, -1)   → 10 9 8 … 1，倒着数
#       range(10, 0)       → 一个数都没有！从 10「往上」数到 0，方向就是反的
#   而且后者不报错，循环安安静静地一轮都不跑。练习 2 你会撞上它。
#
# 【先猜 2】打印 3，不是 6。
#   total = 0 在循环里面，就是「每一轮开头，先把盒子倒空」：
#       第 1 轮：倒空 → 0 + 1 = 1
#       第 2 轮：倒空 → 0 + 2 = 2
#       第 3 轮：倒空 → 0 + 3 = 3
#   前面攒的全被倒掉了 —— 第 2 课说过，= 装进新的，旧的就没了。
#   规矩：只做一次的准备工作，放循环外面；每一轮都要做的事，才缩进进去。
#   print 同理：缩进进循环，每轮打一次；顶格写在外面，只打最后结果。
#   这种 bug 不报错，只是安静地给你一个错的数 —— 跟第 3 课那个缩进坑是同一个坑。
#
# 【先猜 3】3 会一直打下去，永远打不完。「发射！」永远等不到。
#   while 每一轮开头看一眼 n > 0。n 从来没变过，条件就永远成立，
#   它就永远转下去 —— 这叫「死循环」。不报错，只会一直刷屏。
#   真撞上了：按 Ctrl+C 强行打断（会看到 KeyboardInterrupt，那不是 bug，是你按停的）。
#   上面必须装保险丝，就是这个原因：不装的话这个文件会卡死在那里，你永远到不了自测。
#
#   写 while 时问自己一句：「每一轮，有什么东西在把条件往『不成立』那边推？」
#   for 没这个烦恼 —— range 给几个数就转几轮，天然会停。所以：
#       知道要转几轮            → 用 for
#       不知道（比如等人猜对）  → 用 while
#
# 【先猜 4】只打印 1、2。
#   n 到 3 时，先走到 if，条件成立 → break，整个循环当场结束。
#   print(n) 在 break 下面，这一轮根本没轮到它，所以 3 不打；4 以后的轮次也全没了。
#   同样几行，把 print(n) 挪到 if 上面，结果就变成 1 2 3 —— 顺序就是逻辑。
#
#   break 有个兄弟叫 continue：「跳过这一轮剩下的，直接进下一轮」。
#   把上面的 break 换成 continue，会打印 1 2 4 5 7 8 —— 只跳过 3 的倍数，不散场。
#
#
# 【这跟 AI 有什么关系】
#   训练一个模型，骨架就是一个循环：
#       for step in range(10000):
#           猜一次 → 对答案 → 把参数往对的方向拧一点点
#   到阶段 3 你会亲手写出它。那个循环的写法，跟你今天写的 for 一模一样。
#
