# for 就是「挨个拿出来，每个都做一遍」。
# 跟 if 一样：冒号 + 缩进。缩进的那几行，就是每一轮要做的事。
# ch 是随便起的名字 —— 每一轮，这个盒子里自动换成下一个字。
for ch in "你好AI":
    print(ch)

# Python 过文字，是一个字一个字过的。
# 大模型读文字可不是这样 —— 它按 token 切块。那是 B 轨 c01 的事。


# ---------------------------------------------------
# 【先猜 1】想让电脑数数，用 range。下面会打印哪几个数？
#
#     for i in range(5):
#         print(i)
#
#   range(5)，那就是 1 2 3 4 5 呗？
#   停。写下三件事：从几开始、到几结束、一共几个。
# ---------------------------------------------------

for i in range(5):
    print(i)

# 想从 1 数到 5，得这么写：
for i in range(1, 6):
    print(i)


# ---------------------------------------------------
# 循环最常见的用法：攒一个总数。
# 1 + 2 + 3 + … + 100 等于多少？让电脑老老实实加 100 次：
# ---------------------------------------------------
total = 0                     # 循环开始前，先准备一个空盒子
for i in range(1, 101):
    total = total + i         # 每一轮：取出盒子里的数，加上 i，再装回去
print(total)

# total = total + i 可以简写成 total += i，意思一模一样，以后到处都会见到。


# ---------------------------------------------------
# 【先猜 2】有人把 total = 0 挪进了循环里面（看缩进）：
#
#     for i in range(1, 4):
#         total = 0
#         total = total + i
#     print(total)
#
#   本来 1 + 2 + 3 = 6。挪了一行，还是 6 吗？
#   停。在脑子里一轮一轮地跑：每一轮开头，盒子里装的是几？
# ---------------------------------------------------

for i in range(1, 4):
    total = 0
    total = total + i
print(total)


# ---------------------------------------------------
# while 是另一种循环：「只要条件还成立，就再来一轮」。
# 每一轮开头看一眼条件，不成立了才停。
# ---------------------------------------------------
n = 3
while n > 0:
    print(n)
    n = n - 1
print("发射！")


# ---------------------------------------------------
# 【先猜 3】有人少写了一行 —— 忘了 n = n - 1：
#
#     n = 3
#     while n > 0:
#         print(n)
#     print("发射！")
#
#   3 会打印几次？「发射！」还打得出来吗？
# ---------------------------------------------------

# 下面装了一根「保险丝」：转满 5 圈就强行掐断。为什么非装不可，见【原理】。
n = 3
rounds = 0
while n > 0:
    print(n)
    rounds = rounds + 1
    if rounds == 5:
        print(f"…… 转了 {rounds} 圈，n 还是 {n}。保险丝烧断，强行停下")
        break


# ---------------------------------------------------
# 上面保险丝里那个 break，意思是「立刻跳出循环，剩下的轮次全不要了」。
#
# 【先猜 4】这段会打印哪几个数？
#
#     for n in range(1, 10):
#         if n % 3 == 0:
#             break
#         print(n)
#
#   % 是取余数，n % 3 == 0 就是「n 能被 3 整除」。
#   第一个撞上的是 3。那 3 自己，会不会被打出来？
# ---------------------------------------------------

for n in range(1, 10):
    if n % 3 == 0:
        break
    print(n)


