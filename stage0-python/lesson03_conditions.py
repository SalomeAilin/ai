# if 就是「如果」。条件成立，就执行下面缩进的那几行；否则走 else。
# 两样东西不能少：条件后面的冒号 : ，和下一行开头的缩进（4 个空格）。
age = 20
if age >= 18:
    print("成年了")
else:
    print("还没成年")


