# ===================================================
# 【原理】自测完再读
# ===================================================
#
# 【先猜 1】只打印「考试结束」一行。
#   缩进决定了「哪几行属于这个 if」。缩进的两行是 if 的身体，
#   顶格的那行已经走出 if 了，跟条件没关系，永远会执行。
#   别的语言用大括号 { } 圈范围，Python 用缩进 ——
#   空格在这里是语法，不是排版。缩进错了，逻辑就是错的，
#   而且它经常不报错，只是安静地做错事。
#
# 【先猜 2】SyntaxError，而且是「整个文件一行都跑不了」那种。
#   = 是把右边装进左边（第 2 课），if 要的是一个「成不成立」的判断，
#   两码事，所以 Python 直接拒绝。
#   注意它跟第 2 课那个 TypeError 的区别：
#     TypeError    → 跑到那一行才炸，前面的都已经执行完了
#     SyntaxError  → 读都读不懂，整个文件一行都不执行
#   正因为这样，上面才要用 exec() 把它包成一段文字丢进去跑，
#   否则这个演示会把整个 lesson03 卡死在开头，你连第一行输出都看不到。
#
# 【先猜 3】打印 2 行：优秀、及格。
#   两个独立的 if 是两道独立的题，各判各的，互相不知道对方存在。
#   elif 才是「上一个没中，才轮到我」—— 一串 if/elif 里最多只会中一个。
#   成绩分档、价格分级这种「只能选一个」的场景用错，两条都会冒出来。
#
# 【先猜 4】False。
#   文字比大小是按「字典顺序」，一个字符一个字符地比：
#   先比第一个字符，"1" 排在 "9" 前面，胜负当场就定了 ——
#   后面那个 "0" 根本没机会上场。
#
#   这个坑在真实代码里特别致命，因为 input() 拿回来的永远是文字：
#
#       age = input("年龄：")      ← 输入 20，age 是 "20"，不是 20
#       if age > 18:              ← TypeError，文字没法跟数字比
#       if int(age) > 18:         ← 这样才对
#
