x = 5

# exec() 把一段「文字」当代码来跑。这里必须这么写，原因见【原理】。
try:
    exec("if x = 5:\n    print('x 是 5')")
except SyntaxError as e:
    print("报错了 →", e)

# 判断「相等」要用两个等号：
if x == 5:
    print("x == 5 成立")


