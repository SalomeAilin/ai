# 以 # 开头的行叫"注释"，Python 会完全忽略它们。
# 注释是写给人看的，不是写给电脑看的。


# print 是"打印"的意思，它把括号里的内容显示到屏幕上。
# 这是你和程序对话的第一个窗口。
print("你好，世界！")


# 文字要用引号包起来。单引号双引号都行，但要成对。
print('我在学 AI')


# print 也能算数。数字不用加引号。
print(1 + 1)


# 注意这两行的区别 —— 引号改变了一切：
print(1 + 1)      # 输出 2      ← 电脑当成算式算了
print("1 + 1")    # 输出 1 + 1  ← 电脑当成一串文字原样显示


# 一次打印多个东西，用逗号隔开，Python 会自动加空格：
print("2 加 3 等于", 2 + 3)


