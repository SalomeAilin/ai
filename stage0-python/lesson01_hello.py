# 【原理】看完自测再读这段，不然就白猜了
# ===================================================
#
# 加号 + 对不同类型做的是完全不同的事：
#   数字 + 数字  → 相加      1 + 1   得 2
#   文字 + 文字  → 拼接      "1"+"1" 得 11
#
# 乘号 * 也一样：
#   文字 * 数字  → 重复      "5" * 3 得 555
#
# 引号是这一切的开关。加了引号，5 就不再是数量五，
# 而是「一个叫 5 的符号」，跟字母 a 没有本质区别。
#
# 这个区别贯穿你以后写的每一行代码。
