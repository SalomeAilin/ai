# 变量就是一个"盒子"，你给它起个名字，往里装东西。
# 等号 = 的意思不是"相等"，而是"把右边的东西装进左边的盒子"。

name = "小明"
age = 18

print(name)
print(age)


# 盒子里的东西随时可以换：
age = 19
print("过了一年，现在", age, "岁")


# 变量可以互相运算：
price = 25
count = 3
total = price * count
print("总共要花", total, "元")


# ---------------------------------------------------
# 四种最基本的数据类型
# ---------------------------------------------------

a = 10           # int    整数
b = 3.14         # float  小数
c = "你好"        # str    字符串（文字）
d = True         # bool   布尔值，只有 True 和 False 两个取值

# type() 可以查看一个东西是什么类型：
print(type(a))   # <class 'int'>
print(type(b))   # <class 'float'>
print(type(c))   # <class 'str'>
print(type(d))   # <class 'bool'>


# ---------------------------------------------------
# 类型很重要！加号对不同类型的含义完全不同
# ---------------------------------------------------

print(1 + 2)            # 3       数字相加
print("1" + "2")        # 12      文字拼接！不是 3！

# print(1 + "2")        # ← 报错：数字和文字不能相加

# 需要转换类型：
print(1 + int("2"))     # 3       int() 把文字转成数字
print(str(1) + "2")     # 12      str() 把数字转成文字


# ---------------------------------------------------
# f-string：把变量塞进句子里（最常用的写法，务必记住）
# ---------------------------------------------------

name = "小红"
score = 95

# 老办法，麻烦：
print("我是" + name + "，考了" + str(score) + "分")

# 新办法，引号前加个 f，变量用 {} 括起来：
print(f"我是{name}，考了{score}分")

# {} 里还能直接算：
print(f"再考一次的话，两次总分是 {score * 2} 分")


