# 【先猜 2】答案 5。
#   b = a 是把 a 当时的「值」5 抄进 b，不是把两个盒子绑在一起。
#   之后 a 怎么变都跟 b 无关。抄的是内容，不是链接。
#
# 【先猜 3】报错 TypeError。
