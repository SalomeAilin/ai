# ---------------------------------------------------
# 四种基本类型。type() 能看一个东西是什么类型。
# ---------------------------------------------------
print(type(10))       # int    整数
print(type(3.14))     # float  小数
print(type("你好"))    # str    字符串
print(type(True))     # bool   真假，只有 True / False


# ---------------------------------------------------
# 【先猜 3】下面这行会正常输出，还是会报错？
#
#     print(1 + "2")
#
#   想想第 1 课学的：加号对不同类型做的事不一样。
#   那「一个数字」加「一段文字」，它该做哪件事？
# ---------------------------------------------------

try:
    print(1 + "2")
except TypeError as e:
    print("报错了 →", e)
    print("因为 Python 也不知道你想算 3 还是想拼成 12，所以它拒绝猜。")

# 想要哪种，就得自己说清楚：
print(1 + int("2"))    # 转成数字再加
print(str(1) + "2")    # 转成文字再拼


# ---------------------------------------------------
# f-string：往句子里塞变量（最常用，务必记住）
# 引号前加 f，变量用 {} 括起来
# ---------------------------------------------------
name = "小红"
score = 95
print(f"我是{name}，考了{score}分")
print(f"再考一次，两次总分 {score * 2} 分")   # {} 里能直接算


